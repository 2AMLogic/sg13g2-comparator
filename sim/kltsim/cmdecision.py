def expected_keys() -> list[tuple[str, float, float]]:
    return [(p, v, float(t)) for p in ("tt", "ff", "ss", "fs", "sf")
            for v in SUPPLIES_V for t in TEMPERATURES_C]


def _key(corner: dict):
    k = grade_mod._corner_key(corner)
    return None if k is None else (k[0], k[1], float(k[2]))


def load_points(envelope: dict, vcm_v: float | None = None) -> dict:
    """Per grid key: {"corner_id", "values", "problem"}; a rejected point has
    values = None. ``vcm_v`` enables the condition-application probe."""
    points: dict = {}
    for corner in envelope.get("corners") or []:
        key = _key(corner)
        if key is None:
            continue
        problem = grade_mod._corner_problems(corner, BENCH_NAME, GATES)
        idx = None
        if problem is None:
            idx, bad = grade_mod.measurement_index(corner)
            problem = bad
        if problem is None and vcm_v is not None:
            m = (idx or {}).get("vcm_meas")
            if m is None or m.get("value") is None:
                problem = "vcm_meas probe missing"
            elif (isinstance(m["value"], bool) or not isinstance(m["value"], (int, float))
                  or not math.isfinite(m["value"])):
                problem = (f"vcm_meas probe malformed or non-finite ({m['value']!r}); "
                           "condition not verified")
            elif abs(m["value"] - vcm_v) > VCM_TOL_V:
                problem = f"vcm_meas={m['value']} V does not match condition {vcm_v} V"
        values = None
        if problem is None:
            values = {n: (m.get("value")) for n, m in idx.items()}
            for n in ROW3:
                v = values.get(n)
                if not isinstance(v, (int, float)) or not math.isfinite(v):
                    problem, values = f"{n} not reported", None
                    break
        if key in points:
            points[key] = {"corner_id": corner.get("corner_id"), "values": None,
                           "problem": "grid point reported more than once"}
            continue
        points[key] = {"corner_id": corner.get("corner_id"), "values": values, "problem": problem}
    return points


def key_label(key) -> str:
    return grade_mod.key_label(key)


def summarize(points: dict) -> dict:
    """Per-point verdicts and grid min/max for the three Row 3 quantities."""
    keys = expected_keys()
    rows, rejected = [], []
    stats = {n: [] for n in ROW3}
    for k in keys:
        p = points.get(k)
        if p is None:
            rejected.append({"point": key_label(k), "reason": "point missing from the envelope"})
            continue
        if p["values"] is None:
            rejected.append({"point": key_label(k), "reason": p["problem"]})
            continue
        v = p["values"]
        row = {"point": key_label(k), "key": list(k), "corner_id": p["corner_id"]}
        for n, spec in ROW3.items():
            row[n] = v[n]
            row[f"{n}_target"] = "PASS" if v[n] <= spec["target"] else "FAIL"
            if spec["stretch"] is not None:
                row[f"{n}_stretch"] = "PASS" if v[n] <= spec["stretch"] else "FAIL"
            stats[n].append((v[n], key_label(k)))
        row["resolve_decades"] = v.get("resolve_decades")
        row["p_avg_uw"] = v.get("p_avg_uw")
        rows.append(row)
    agg = {}
    for n, vals in stats.items():
        if vals:
            lo, hi = min(vals), max(vals)
            agg[n] = {"min": lo[0], "min_point": lo[1], "max": hi[0], "max_point": hi[1],
                      "target": ROW3[n]["target"],
                      "target_fail_points": sum(1 for r in rows if r[f"{n}_target"] == "FAIL"),
                      "stretch": ROW3[n]["stretch"],
                      "stretch_fail_points": (sum(1 for r in rows if r[f"{n}_stretch"] == "FAIL")
                                              if ROW3[n]["stretch"] is not None else None)}
    decades = [r["resolve_decades"] for r in rows if isinstance(r["resolve_decades"], (int, float))]
    return {"points_expected": len(keys), "points_valid": len(rows), "rows": rows,
            "rejected": rejected, "grid": agg,
            "resolve_decades_min": min(decades) if decades else None}


def reproduction(nominal_env: dict, reference_env: dict) -> dict:
    """Exact comparison of every reference measurement at every expected point.

    A reference measurement absent from the nominal envelope is a mismatch;
    only an extra nominal measurement (e.g. the ``vcm_meas`` probe) is allowed."""
    def table(env):
        out = {}
        for c in env.get("corners") or []:
            k = _key(c)
            idx, _ = grade_mod.measurement_index(c)
            if k is not None and idx is not None:
                out[k] = {n: m.get("value") for n, m in idx.items()}
        return out
    a, b = table(nominal_env), table(reference_env)
    mismatches, compared = [], 0
    for k in expected_keys():
        if k not in a or k not in b:
            mismatches.append({"point": key_label(k), "reason": "missing in one envelope"})
            continue
        for n in sorted(b[k]):
            if n not in a[k]:
                mismatches.append({"point": key_label(k), "measurement": n,
                                   "reason": "reference measurement missing from nominal"})
                continue
            compared += 1
            if a[k][n] != b[k][n]:
                mismatches.append({"point": key_label(k), "measurement": n,
                                   "nominal": a[k][n], "reference": b[k][n]})
    shared = sorted(set(next(iter(a.values()), {})) & set(next(iter(b.values()), {})))
    return {"bit_identical": not mismatches and compared > 0, "values_compared": compared,
            "shared_measurements": shared, "mismatches": mismatches}


def _load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def _remote(env: dict) -> dict:
    r = (env.get("environment") or {}).get("remote") or {}
    return {k: r.get(k) for k in ("job_id", "instance_type", "lifecycle", "state", "exit_code",
                                  "elapsed_seconds")}


def compare_series(series: Path, reference_campaign: str = REFERENCE_CAMPAIGN) -> dict:
    ref_path = (build_mod.SIM_DIR / "klt-corner-verification" / "campaigns" / reference_campaign
                / "regeneration.envelope.json")
    ref_env = _load_json(ref_path)
    ref_points = load_points(ref_env)
    result: dict = {"issue": 164, "series": series.name, "reference_campaign": reference_campaign,
                    "conditions": {}}
    envs = {}
    for cond in CONDITIONS:
        env_path = series / cond.name / f"{TAG}.envelope.json"
        if not env_path.is_file():
            result["conditions"][cond.name] = {"missing": True}
            continue
        envs[cond.name] = _load_json(env_path)
        s = summarize(load_points(envs[cond.name], cond.vcm_v()))
        s["vcm_v"] = cond.vcm_v()
        s["remote"] = _remote(envs[cond.name])
        result["conditions"][cond.name] = s
    if NOMINAL in envs:
        result["reproduction"] = reproduction(envs[NOMINAL], ref_env)
    nom = result["conditions"].get(NOMINAL, {})
    nom_rows = {tuple(r["key"]): r for r in nom.get("rows", [])} if nom else {}
    for name, c in result["conditions"].items():
        if c.get("missing") or name == NOMINAL:
            continue
        deltas = []
        for r in c["rows"]:
            n = nom_rows.get(tuple(r["key"]))
            if n is None:
                continue
            deltas.append({"point": r["point"], **{f"d_{q}": r[q] - n[q] for q in ROW3}})
        c["delta_vs_nominal"] = deltas
        c["delta_summary"] = {
            q: {"min": min(d[f"d_{q}"] for d in deltas), "max": max(d[f"d_{q}"] for d in deltas)}
            for q in ROW3} if deltas else None
    result["reference_points_valid"] = sum(1 for p in ref_points.values() if p["values"] is not None)
    return result


def render_markdown(result: dict) -> str:
    L = [f"# Decision time across the CM band (issue #164), series `{result['series']}`", "",
         "Evidence for the DR-0004 candidate CM-range row. Graded against the unchanged DR-0002 "
         "Row 3 bounds; Stretch (td_od50 <= 0.8 ns) reported. Rejected points are named with "
         "their reason; nothing is substituted.", ""]
    rep = result.get("reproduction")
    if rep:
        L += [f"**vcm-nom reproduction vs `{result['reference_campaign']}`:** "
              f"{'BIT-IDENTICAL' if rep['bit_identical'] else 'NOT IDENTICAL'} "
              f"({rep['values_compared']} values compared across "
              f"{len(rep['shared_measurements'])} shared measurements, "
              f"{len(rep['mismatches'])} mismatches).", ""]
    L += ["| condition | vcm (V) | valid | td_od50 ns (min..max) | tau ps (min..max) | "
          "td_od01 ns (min..max) | Target fails (50mV/tau/0.1mV) | Stretch fails (50mV) | "
          "min decades | batch job |", "|---|---|---|---|---|---|---|---|---|---|"]
    for name, c in result["conditions"].items():
        if c.get("missing"):
            L.append(f"| {name} | | not run | | | | | | | |")
            continue
        g = c["grid"]
        def rng(q):
            return f"{g[q]['min']:.4g}..{g[q]['max']:.4g}" if q in g else "n/a"
        tf = "/".join(str(g[q]["target_fail_points"]) if q in g else "n/a" for q in ROW3)
        sf = g["td_od50_ns"]["stretch_fail_points"] if "td_od50_ns" in g else "n/a"
        md = c["resolve_decades_min"]
        L.append(f"| {name} | {c['vcm_v']} | {c['points_valid']}/{c['points_expected']} | "
                 f"{rng('td_od50_ns')} | {rng('tau_ps')} | {rng('td_od01_ns')} | {tf} | {sf} | "
                 f"{'n/a' if md is None else f'{md:.3g}'} | {c['remote'].get('job_id')} |")
    L.append("")
    for name, c in result["conditions"].items():
        if c.get("missing"):
            continue
        L += [f"## {name}", ""]
        for q, g in c["grid"].items():
            L.append(f"- {q}: min {g['min']:.5g} ({g['min_point']}), max {g['max']:.5g} "
                     f"({g['max_point']}); Target {g['target']} failed at "
                     f"{g['target_fail_points']} point(s)")
        if c.get("rejected"):
            L += ["", "Rejected points:"] + [f"- `{r['point']}`: {r['reason']}" for r in c["rejected"]]
        else:
            L += ["", "No rejected points."]
        if c.get("delta_summary"):
            L += ["", "Per-point change versus `vcm-nom` (min..max): " + "; ".join(
                f"{q} {s['min']:+.4g}..{s['max']:+.4g}" for q, s in c["delta_summary"].items())]
        L += ["", "| point | td_od50 ns | tau ps | td_od01 ns |"
              + (" d td_od50 | d tau | d td_od01 |" if c.get("delta_vs_nominal") else ""),
              "|---|---|---|---|" + ("---|---|---|" if c.get("delta_vs_nominal") else "")]
        dmap = {d["point"]: d for d in c.get("delta_vs_nominal", [])}
        for r in c["rows"]:
            line = f"| {r['point']} | {r['td_od50_ns']:.5g} | {r['tau_ps']:.5g} | {r['td_od01_ns']:.5g} |"
            d = dmap.get(r["point"])
            if d:
                line += f" {d['d_td_od50_ns']:+.4g} | {d['d_tau_ps']:+.4g} | {d['d_td_od01_ns']:+.4g} |"
            L.append(line)
        L.append("")
    return "\n".join(L) + "\n"
