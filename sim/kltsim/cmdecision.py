EXPERIMENT_DIR = build_mod.SIM_DIR / "comparator-decision-cm-band"
SERIES_DIR = EXPERIMENT_DIR / "campaigns"

BENCH_NAME = "regeneration"
BODY_NAME = f"{BENCH_NAME}.body.spice"
REQUEST_NAME = f"{BENCH_NAME}.request.json"
TAG = BENCH_NAME

REFERENCE_CAMPAIGN = "20261009-d73a9ac"

Condition = cmband.Condition
CONDITIONS = cmband.CONDITIONS
NOMINAL = cmband.NOMINAL
condition = cmband.condition
VCM_LINE = cmband.VCM_LINE
VCM_LINE_CM = cmband.VCM_LINE_CM
CONDITION_MARK = "* ---- CM-band condition (issue #164):"

VCM_PROBE = cmband.VCM_PROBE
VCM_TOL_V = cmband.VCM_TOL_V

#: DR-0002 Row 3 Targets (unchanged) and the 50 mV Stretch.
ROW3 = {
    "td_od50_ns": {"label": "decision time @ 50 mV", "unit": "ns", "target": 1.5, "stretch": 0.8},
    "tau_ps": {"label": "regeneration tau", "unit": "ps", "target": 250.0, "stretch": None},
    "td_od01_ns": {"label": "decision time @ 0.1 mV", "unit": "ns", "target": 2.0,
                   "stretch": None},
}
GATES = ["dout_od50_first", "dout_od1_first", "dout_od01_first",
         "dout_od50_end", "dout_od1_end", "dout_od01_end"]
REPORTED = ("td_od50_ns", "td_od1_ns", "td_od01_ns", "tau_ps", "resolve_decades", "p_avg_uw")
EXPECTED_POINTS = 45


class DecisionCmError(RuntimeError):
    pass


def bench_for(cond: Condition):
    return dataclasses.replace(
        REGENERATION,
        measurements=REGENERATION.measurements + (VCM_PROBE,),
        description=(
            f"EVIDENCE FOR DR-0004 (issue #164), condition {cond.name}: decision time at "
            f"50 mV / 1 mV / 0.1 mV overdrive and tau at input common mode "
            f"dut_vcm{cond.delta_v * 1e3:+.0f} mV; the issue #62 regeneration bench "
            "otherwise unchanged. Graded against the unchanged DR-0002 Row 3 bounds."
        ),
    )


def apply_transform(body: str, cond: Condition) -> str:
    lines = body.split("\n")
    hits = [i for i, line in enumerate(lines) if line == VCM_LINE]
    if len(hits) != 1:
        raise DecisionCmError(
            f"expected exactly one `{VCM_LINE}` line in the regeneration body, found {len(hits)}")
    i = hits[0]
    lines[i:i + 1] = [
        f"{CONDITION_MARK} {cond.name}, input common mode = dut_vcm + vcm_delta",
        f".param vcm_delta={cond.delta_v!r}",
        VCM_LINE_CM,
    ]
    lines[0] = (f"* {BENCH_NAME} -- klt sim netlist BODY (sim/comparator-decision-cm-band, "
                f"issue #164) condition={cond.name} vcm_delta={cond.delta_v!r}")
    lines[1] = ("* GENERATED by `python3 sim/run_decision_cm_band.py build` from the issue #62 "
                "regeneration body (sim/kltsim/cmdecision.py) -- do not edit;")
    return "\n".join(lines)


def undo_transform(body: str) -> str:
    out = []
    for line in body.split("\n"):
        if line.startswith(CONDITION_MARK) or line.startswith(".param vcm_delta="):
            continue
        out.append(VCM_LINE if line == VCM_LINE_CM else line)
    return "\n".join(out)


def compose_body(cond: Condition, osdi_dir: str = build_mod.BATCH_OSDI_DIR) -> str:
    return apply_transform(build_mod.compose_body(REGENERATION, osdi_dir), cond)


def condition_metadata(cond: Condition) -> dict:
    return {
        "issue": 164,
        "name": cond.name,
        "vcm_delta_v": cond.delta_v,
        "vcm_v": cond.vcm_v(),
        "scope": "evidence for the DR-0004 candidate CM-range row (no ratified range)",
    }


def compose_request(cond: Condition, backend: str = "batch") -> dict:
    bench = bench_for(cond)
    request = build_mod.compose_request(bench, BODY_NAME, backend)
    request["_comment"] = [
        f"sg13g2-comparator -- klt sim request, CM-band decision-time condition `{cond.name}` "
        "(issue #164).",
        "GENERATED by `python3 sim/run_decision_cm_band.py build`; the committed copy is "
        "byte-for-byte what was submitted.",
        bench.description,
        "Measurements, limits and analysis are the issue #62 regeneration bench's, plus the "
        "vcm_meas probe.",
    ]
    request["_condition"] = condition_metadata(cond)
    return request


def write_condition_inputs(cond: Condition, out_dir: Path, *, backend: str = "batch"
                           ) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    body = out_dir / BODY_NAME
    body.write_text(compose_body(cond), encoding="utf-8")
    req = out_dir / REQUEST_NAME
    req.write_text(json.dumps(compose_request(cond, backend), indent=2) + "\n", encoding="utf-8")
    return body, req


