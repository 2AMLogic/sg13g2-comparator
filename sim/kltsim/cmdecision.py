"""Decision time / metastability across a bounded input common-mode band (issue #164).

EVIDENCE FOR THE DR-0004 CANDIDATE CM-RANGE ROW, NOT A RATIFICATION. The
issue #62 ``regeneration`` bench (``sim/kltsim/benches.py``) is reused
unchanged in every respect but one line of its netlist body, using the same
mechanism as issue #79 (``sim/kltsim/cmband.py``):

    vcm cm 0 dc {dut_vcm}   ->   .param vcm_delta=<d>
                                 vcm cm 0 dc {dut_vcm+vcm_delta}

for all three conditions, the nominal one included (``vcm_delta=0.0``). One
added probe (``vcm_meas``) records the common mode actually simulated. The
deterministic bench has no Monte Carlo: one request per condition, 5 process
x 3 supply x 3 temperature = 45 points.

Each point is graded against the UNCHANGED ratified DR-0002 Row 3 bounds
(td_od50 <= 1.5 ns, tau <= 250 ps, td_od01 <= 2.0 ns; Stretch td_od50 <=
0.8 ns reported). A point whose corner errored, whose probes disagree with
its corner, whose decision-polarity gates failed or whose condition probe
disagrees with ``dut_vcm + vcm_delta`` is REJECTED with its reason; no value
is substituted for it.

The ``vcm-nom`` condition is a reproduction gate: every shared measurement
must equal the issue #62 campaign's ``regeneration`` envelope exactly.
"""

